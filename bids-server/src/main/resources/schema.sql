CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,

    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,

    mobile_phone VARCHAR(20) NOT NULL,

    city VARCHAR(50),
    street VARCHAR(100),
    zip_code VARCHAR(10),

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    seller_id BIGINT NOT NULL,

    name VARCHAR(255) NOT NULL,
    description TEXT,
    category VARCHAR(100) NOT NULL,
    delivery_location VARCHAR(255) NOT NULL,
    image_url VARCHAR(2048),

    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,

    starting_price DECIMAL(19, 2) NOT NULL,
    current_price DECIMAL(19, 2) NOT NULL,

    leading_bid_id BIGINT,

    CONSTRAINT fk_products_seller
        FOREIGN KEY (seller_id) REFERENCES users(id)

);

CREATE TABLE IF NOT EXISTS bids (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL,
    bidder_id BIGINT NOT NULL,

    max_amount DECIMAL(19, 2) NOT NULL,
    bid_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_bids_product
        FOREIGN KEY (product_id) REFERENCES products(id),

    CONSTRAINT fk_bids_bidder
        FOREIGN KEY (bidder_id) REFERENCES users(id)
);

ALTER TABLE products
ADD CONSTRAINT IF NOT EXISTS fk_products_leading_bid
FOREIGN KEY (leading_bid_id) REFERENCES bids(id);