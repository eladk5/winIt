package com.example.bids_server.repository;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;
import java.sql.PreparedStatement;
import java.util.Optional;

@Repository
public class UsersRepository {

    private final JdbcTemplate jdbcTemplate;

    public UsersRepository(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    /**
     * Finds a user id by username.
     * Returns Optional.empty() if no such user exists.
     */
    public Optional<Long> findIdByUsername(String username) {
        String sql = "SELECT id FROM users WHERE username = ?";

        return jdbcTemplate.query(sql, rs -> {
            if (!rs.next()) {
                return Optional.empty();
            }
            return Optional.of(rs.getLong("id"));
        }, username);
    }

    /**
     * Inserts a new user into the database and returns the generated id.
     * Note: created_at is generated by the DB (DEFAULT CURRENT_TIMESTAMP).
     * 
     * @return the generated user id
     */
    public long saveUser(
            String username,
            String passwordHash,
            String firstName,
            String lastName,
            String mobilePhone,
            String city,
            String street,
            String zipCode) {
        String sql = """
                INSERT INTO users (username, password_hash, first_name, last_name, mobile_phone, city, street, zip_code)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                """;

        KeyHolder keyHolder = new GeneratedKeyHolder();

        jdbcTemplate.update(connection -> {
            PreparedStatement ps = connection.prepareStatement(sql, new String[] { "ID" });
            ps.setString(1, username);
            ps.setString(2, passwordHash);
            ps.setString(3, firstName);
            ps.setString(4, lastName);
            ps.setString(5, mobilePhone);
            ps.setString(6, city);
            ps.setString(7, street);
            ps.setString(8, zipCode);
            return ps;
        }, keyHolder);

        Number key = keyHolder.getKey();
        if (key == null) {
            throw new IllegalStateException("Failed to retrieve generated user id after insert");
        }
        return key.longValue();
    }

    /**
     * Returns the stored password hash for the given username.
     * If the user does not exist, returns Optional.empty().
     */
    public Optional<String> findPasswordHashByUsername(String username) {
        String sql = "SELECT password_hash FROM users WHERE username = ?";

        return jdbcTemplate.query(sql, rs -> {
            if (!rs.next()) {
                return Optional.empty();
            }
            return Optional.of(rs.getString("password_hash"));
        }, username);
    }

}
